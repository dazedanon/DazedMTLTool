'use strict';
const assert = require('assert/strict');
const vm = require('vm');
const fs = require('fs');
const api = require('./panel_bounds.cjs');
const {pixelBounds, transformRect, measure, evaluateReport} = api;
const image = {width: 8, height: 6, data: new Uint8ClampedArray(8 * 6 * 4)};
for (let y = 1; y < 5; y++) for (let x = 2; x < 7; x++) image.data.set([100, 100, 150, 229], (y * 8 + x) * 4);
image.data.set([255, 255, 255, 255], 0); // title must not enlarge the panel's bound
const panel = pixelBounds(image, (r, g, b, a) => a > 64 && b > r + 5 && b > g + 5 && r > 60 && r < 230);
assert.deepEqual(panel, {left: 2, top: 1, right: 7, bottom: 5});
assert.throws(() => pixelBounds(image, () => false), /no pixels/);
assert.throws(() => pixelBounds({...image, data: [0]}, () => true), /RGBA/);
assert.deepEqual(transformRect(panel, {a: -2, b: 0, c: 0, d: 3, tx: 30, ty: -1}), {left: 16, top: 2, right: 26, bottom: 14});
assert.throws(() => transformRect(panel, {a: 1, b: .1, c: 0, d: 1, tx: 0, ty: 0}), /rotation/);
const ink = {left: 3, top: 2, right: 8, bottom: 4};
assert.equal(measure({left: 0, top: 0, right: 16, bottom: 9}, ink).pass, true);
assert.equal(measure(panel, ink).pass, false); // the canvas-only false positive
assert.throws(() => measure(panel, {...ink, right: NaN}), /invalid/);
assert.throws(() => measure(panel, {...ink, right: 3}), /empty/);
assert.throws(() => measure(panel, ink, NaN), /margin/);
const row = {map: 4, profile: 'reported', index: 102, panel, displayed: ink, pass: true, margins: {right: 999}};
assert.equal(evaluateReport({rows: [row], engineError: ''}, 0, 1).pass, false);
assert.throws(() => evaluateReport({rows: [], engineError: ''}, 0, 1), /No observed/);
assert.throws(() => evaluateReport({rows: [row]}, 0, 1), /engine-error/);
assert.equal(evaluateReport({rows: [row]}, 0, 1, {allowMissingHealth: true}).engineErrorObserved, false);
assert.throws(() => evaluateReport({rows: [row], engineError: 0}, 0, 1, {allowMissingHealth: true}), /engine-error/);
assert.throws(() => evaluateReport({rows: [row, row], engineError: ''}, 0, 2), /duplicate/);
const good = {...row, displayed: {left: 3, top: 2, right: 6, bottom: 4}};
assert.equal(evaluateReport({rows: [good], engineError: ''}, 1, 1).pass, true);
assert.equal(evaluateReport({rows: [good], engineError: 'Engine caught error'}, 1, 1).pass, false);
assert.equal(evaluateReport({rows: [good], engineError: ''}, 1, 2).pass, false);
const browser = {};
vm.runInNewContext(fs.readFileSync(require.resolve('./panel_bounds.cjs'), 'utf8'), browser);
assert.equal(typeof browser.GameTranslationPanelBounds.measure, 'function');
const nw = {module: {exports: {}}, require: {main: null}};
vm.runInNewContext(fs.readFileSync(require.resolve('./panel_bounds.cjs'), 'utf8'), nw);
assert.equal(typeof nw.GameTranslationPanelBounds.measure, 'function');
assert.equal(nw.module.exports, nw.GameTranslationPanelBounds);
console.log('Painted-panel pixel, transform, fail-closed and evidence-replay tests passed.');
